param(
    [Parameter(Mandatory = $true)]
    [string]$SceneRoot,

    [Parameter(Mandatory = $true)]
    [string]$ArtRoot,

    [string]$Output = ''
)

$ErrorActionPreference = 'Stop'

Add-Type -AssemblyName System.Drawing

if (-not (Test-Path -LiteralPath $SceneRoot)) { throw "SceneRoot does not exist: $SceneRoot" }
if (-not (Test-Path -LiteralPath $ArtRoot)) { throw "ArtRoot does not exist: $ArtRoot" }
if ([string]::IsNullOrWhiteSpace($Output)) { $Output = Join-Path $PSScriptRoot '..\src\zhiyi_assets.h' }

Add-Type -ReferencedAssemblies 'System.Drawing' -TypeDefinition @'
using System;
using System.Drawing;
using System.IO;

public static class ZhiYiRgb565Writer
{
    public static void WriteArray(StreamWriter writer, string name, string[] paths, bool chromaKeyGreen)
    {
        if (paths == null || paths.Length == 0)
            throw new ArgumentException("No frames provided for " + name);

        using (var first = new Bitmap(paths[0]))
        {
            int width = first.Width;
            int height = first.Height;
            int pixels = width * height;
            writer.WriteLine("// " + name + ": " + paths.Length + " frames of " + width + "x" + height);
            writer.WriteLine("static const uint16_t PROGMEM " + name + "[" + paths.Length + "][" + pixels + "] = {");

            foreach (string path in paths)
            {
                using (var bitmap = new Bitmap(path))
                {
                    if (bitmap.Width != width || bitmap.Height != height)
                        throw new InvalidOperationException("Mismatched frame size: " + path);

                    writer.Write("  {");
                    int written = 0;
                    for (int y = 0; y < height; y++)
                    {
                        for (int x = 0; x < width; x++)
                        {
                            Color color = bitmap.GetPixel(x, y);
                            ushort rgb565;
                            if (chromaKeyGreen && color.G > 230 && color.R < 25 && color.B < 25)
                            {
                                rgb565 = 0;
                            }
                            else
                            {
                                rgb565 = (ushort)(((color.R & 0xF8) << 8) | ((color.G & 0xFC) << 3) | (color.B >> 3));
                            }

                            if (written > 0)
                                writer.Write(",");
                            if (written > 0 && written % 12 == 0)
                                writer.Write("\n   ");
                            writer.Write("0x" + rgb565.ToString("X4"));
                            written++;
                        }
                    }
                    writer.WriteLine("},");
                }
            }

            writer.WriteLine("};");
            writer.WriteLine();
        }
    }
}
'@

function Get-Frames([string]$Path, [string]$Pattern) {
    return @(Get-ChildItem -LiteralPath $Path -File -Filter $Pattern |
        Sort-Object { [int]([regex]::Match($_.BaseName, '(\d+)$').Groups[1].Value) } |
        ForEach-Object { $_.FullName })
}

function Add-Frames([System.IO.StreamWriter]$Writer, [string]$Name, [string]$Path, [string]$Pattern, [bool]$ChromaKeyGreen) {
    $frames = Get-Frames $Path $Pattern
    [ZhiYiRgb565Writer]::WriteArray($Writer, $Name, [string[]]$frames, $ChromaKeyGreen)
}

function Get-DayWalkFrames([string]$Path, [string]$Pattern) {
    # Keep the walking sequence and each segment's edge turn poses. These four
    # front-facing middle-turn frames interrupt the side-walk loop visually.
    return @((Get-Frames $Path $Pattern) | Where-Object {
        $index = [int]([regex]::Match([IO.Path]::GetFileNameWithoutExtension($_), '(\d+)$').Groups[1].Value)
        $index -notin @(23, 27, 61, 65)
    })
}

$Output = [IO.Path]::GetFullPath($Output)
$outputDirectory = Split-Path -Parent $Output
New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null

$utf8 = [System.Text.UTF8Encoding]::new($false)
$writer = [System.IO.StreamWriter]::new($Output, $false, $utf8)
try {
    $writer.WriteLine('// Generated by scripts/build_zhiyi_assets.ps1. Do not edit by hand.')
    $writer.WriteLine('#pragma once')
    $writer.WriteLine()

    $forest1 = (Get-ChildItem -LiteralPath $SceneRoot -Directory -Recurse | Where-Object { $_.Name -like 'forest1-*' } | Select-Object -First 1).FullName
    $forest2 = (Get-ChildItem -LiteralPath $SceneRoot -Directory -Recurse | Where-Object { $_.Name -like 'forest2-*' } | Select-Object -First 1).FullName
    if (-not $forest1 -or -not $forest2) { throw 'Could not locate forest scene folders.' }
    [ZhiYiRgb565Writer]::WriteArray($writer, 'zhiyi_forest1_off',  [string[]](Get-DayWalkFrames $forest1 'forest1_off_*.png'),  $false)
    [ZhiYiRgb565Writer]::WriteArray($writer, 'zhiyi_forest1_cape', [string[]](Get-DayWalkFrames $forest1 'forest1_cape_*.png'), $false)
    Add-Frames $writer 'zhiyi_forest2_off'  $forest2 'forest2_off_*.png'  $false
    Add-Frames $writer 'zhiyi_forest2_cape' $forest2 'forest2_cape_*.png' $false

    # The revised pack deliberately contains only valid interaction positions.
    # roomwhite stays with the original white-dot room selector.
    $roomPaths = @{}
    foreach ($room in @('roomgray', 'roomred', 'roomblue', 'roomgreen')) {
        $roomPaths[$room] = (Get-ChildItem -LiteralPath $SceneRoot -Directory -Recurse | Where-Object { $_.Name -eq $room } | Select-Object -First 1).FullName
        if (-not $roomPaths[$room]) { throw "Could not locate $room." }
    }

    Add-Frames $writer 'zhiyi_roomgray_computer_off'  $roomPaths['roomgray'] 'roomgray_off_p5.png'   $false
    Add-Frames $writer 'zhiyi_roomgray_computer_cape' $roomPaths['roomgray'] 'roomgray_cape_p5.png'  $false
    Add-Frames $writer 'zhiyi_roomgray_bed_off'       $roomPaths['roomgray'] 'roomgray_off_p9.png'   $false
    Add-Frames $writer 'zhiyi_roomgray_bed_cape'      $roomPaths['roomgray'] 'roomgray_cape_p9.png'  $false
    Add-Frames $writer 'zhiyi_roomgray_exit_off'      $roomPaths['roomgray'] 'roomgray_off_p10.png'  $false
    Add-Frames $writer 'zhiyi_roomgray_exit_cape'     $roomPaths['roomgray'] 'roomgray_cape_p10.png' $false

    Add-Frames $writer 'zhiyi_roomred_food_off'       $roomPaths['roomred'] 'roomred_off_p4.png'     $false
    Add-Frames $writer 'zhiyi_roomred_food_cape'      $roomPaths['roomred'] 'roomred_cape_p4.png'    $false
    Add-Frames $writer 'zhiyi_roomred_exit_off'       $roomPaths['roomred'] 'roomred_off_p6.png'     $false
    Add-Frames $writer 'zhiyi_roomred_exit_cape'      $roomPaths['roomred'] 'roomred_cape_p6.png'    $false

    Add-Frames $writer 'zhiyi_roomblue_bath_off'      $roomPaths['roomblue'] 'roomblue_off_p9.png'   $false
    Add-Frames $writer 'zhiyi_roomblue_bath_cape'     $roomPaths['roomblue'] 'roomblue_cape_p9.png'  $false
    Add-Frames $writer 'zhiyi_roomblue_exit_off'      $roomPaths['roomblue'] 'roomblue_off_p11.png'  $false
    Add-Frames $writer 'zhiyi_roomblue_exit_cape'     $roomPaths['roomblue'] 'roomblue_cape_p11.png' $false

    Add-Frames $writer 'zhiyi_roomgreen_swing_off'    $roomPaths['roomgreen'] 'roomgreen_off_p9.png'  $false
    Add-Frames $writer 'zhiyi_roomgreen_swing_cape'   $roomPaths['roomgreen'] 'roomgreen_cape_p9.png' $false
    Add-Frames $writer 'zhiyi_roomgreen_exit_off'     $roomPaths['roomgreen'] 'roomgreen_off_p10.png' $false
    Add-Frames $writer 'zhiyi_roomgreen_exit_cape'    $roomPaths['roomgreen'] 'roomgreen_cape_p10.png' $false

    Add-Frames $writer 'zhiyi_eat'       (Join-Path $ArtRoot 'eat')   'eat_*.png'       $true
    Add-Frames $writer 'zhiyi_sleep_off' (Join-Path $ArtRoot 'sleep') 'sleep_off_*.png' $true
    Add-Frames $writer 'zhiyi_sleep_cape' (Join-Path $ArtRoot 'sleep') 'sleep_cape_*.png' $true
}
finally {
    $writer.Dispose()
}

Write-Host "Generated $Output"
